//! `cargo xtask public-parity` writes docs/arc-settings-parity.md, the public
//! view of the Arc Settings parity tables in docs/roadmap/arc-settings-parity.md
//! (which public snapshots leave out). Each row keeps its area, ID, the Arc
//! option's name, its status words and its optional last-column `Public note`;
//! references, receipts and acceptance notes stay in the roadmap.
//!
//! A parity table is one whose second column is the Arc reference (its header
//! starts with "Reference"). Tables of Crossbow's own additions have no Arc
//! option and stay out. Anything the page can't place, such as an unknown
//! status word or a note naming a file, stops the command with the row.

use std::path::Path;

pub const SOURCE: &str = "docs/roadmap/arc-settings-parity.md";
pub const OUTPUT: &str = "docs/arc-settings-parity.md";
const NOTE: &str = "Public note";

/// Every status phrase a row may use, in legend order. A status cell may join
/// two with ` / ` (both apply) or ` + ` (the second adds to the first).
const LEGEND: [(&str, &str); 7] = [
    ("SRC", "Crossbow's source has a matching control and action; the note names any difference."),
    ("PART", "Part of the option exists; some of its behaviour or scope differs or is missing."),
    ("PARTIAL SRC", "The main part of the option is built; the note says what is not."),
    ("NATIVE PARTIAL", "Part of it has also been checked in a built app on a Mac."),
    ("NONE", "Crossbow has no matching control yet."),
    ("DISC", "Arc has this preference, but where and how Arc's Settings show it is still to be confirmed."),
    ("OUT", "Left out on purpose."),
];

const HEAD: &str = "# Arc Settings parity

Generated by `cargo xtask public-parity` from the maintainers' own tables, which aren't published, so don't edit this page by hand: propose a change in an issue or pull request, and the maintainers will make it in their tables.

How Crossbow's Settings compare with those of Arc for macOS 1.168.0, option by option. Each status describes Crossbow's source code. A status doesn't say the option was checked in a signed release on a Mac; NATIVE PARTIAL marks the rows where part of it was.
";

const JOINED: &str = "Two statuses joined by `/` both apply, as in NONE / DISC: no control yet, and Arc's placement still to be confirmed. `+` adds to the first, as in SRC + NATIVE PARTIAL.
";

pub fn run(args: &[String], root: &Path) -> Result<(), String> {
    if !args.is_empty() {
        return Err("usage: cargo xtask public-parity".into());
    }
    let source = std::fs::read_to_string(root.join(SOURCE)).map_err(|e| format!("{SOURCE}: {e}"))?;
    let (page, count) = render(&source)?;
    std::fs::write(root.join(OUTPUT), page).map_err(|e| format!("{OUTPUT}: {e}"))?;
    println!("wrote {OUTPUT}: {count} rows");
    Ok(())
}

#[derive(Debug, PartialEq)]
struct Row {
    area: String,
    id: String,
    option: String,
    status: String,
    note: String,
}

/// The public page for `source`, and how many rows it holds.
pub fn render(source: &str) -> Result<(String, usize), String> {
    let rows = rows(source)?;
    if rows.is_empty() {
        return Err(format!("{SOURCE} has no parity table"));
    }
    let mut page = String::from(HEAD);
    page.push_str("\n| Status | Meaning |\n| --- | --- |\n");
    for (word, meaning) in LEGEND {
        page.push_str(&format!("| {word} | {meaning} |\n"));
    }
    page.push('\n');
    page.push_str(JOINED);
    page.push_str("\n| Area | ID | Arc option | Status | Note |\n| --- | --- | --- | --- | --- |\n");
    for row in &rows {
        page.push_str(&format!("| {} | {} | {} | {} | {} |\n", row.area, row.id, row.option, row.status, row.note));
    }
    Ok((page, rows.len()))
}

struct Columns {
    width: usize,
    status: usize,
    note: bool,
}

enum Table {
    Outside,
    Other,
    Parity(Columns),
}

fn rows(source: &str) -> Result<Vec<Row>, String> {
    let mut rows = Vec::new();
    let mut area = String::new();
    let mut table = Table::Outside;
    for (index, line) in source.lines().enumerate() {
        let at = |what: String| format!("{SOURCE}:{}: {what}", index + 1);
        if let Some(heading) = line.strip_prefix("## ") {
            let numbered = heading.split_once(". ").filter(|(n, _)| !n.is_empty() && n.bytes().all(|b| b.is_ascii_digit()));
            area = numbered.map_or(heading, |(_, rest)| rest).trim().to_owned();
            table = Table::Outside;
            continue;
        }
        if !line.starts_with('|') {
            table = Table::Outside;
            continue;
        }
        let cells = cells(line).map_err(at)?;
        match &table {
            Table::Outside => {
                table = if cells[0] == "ID" && cells.get(1).is_some_and(|c| c.starts_with("Reference")) {
                    let status = cells.iter().position(|c| c.to_ascii_lowercase().contains("status")).ok_or_else(|| at("the parity table has no status column".into()))?;
                    let note = cells.iter().position(|c| c == NOTE);
                    if note.is_some_and(|i| i + 1 != cells.len()) {
                        return Err(at(format!("`{NOTE}` must be the last column")));
                    }
                    Table::Parity(Columns { width: cells.len(), status, note: note.is_some() })
                } else {
                    Table::Other
                };
            }
            Table::Other => {}
            Table::Parity(columns) => {
                if cells.iter().all(|c| !c.is_empty() && c.bytes().all(|b| b == b'-' || b == b':')) {
                    continue;
                }
                let short = columns.note && cells.len() + 1 == columns.width;
                if cells.len() != columns.width && !short {
                    return Err(at(format!("the row has {} cells; its table has {}", cells.len(), columns.width)));
                }
                let id = cells[0].clone();
                let note = if columns.note && !short { cells[columns.width - 1].clone() } else { String::new() };
                if !note.is_empty() {
                    check_note(&note).map_err(|why| at(format!("{id}'s {NOTE} {why}")))?;
                }
                let option = option_name(&cells[1]).map_err(|why| at(format!("{id}'s option name {why}")))?;
                let status = status_words(&cells[columns.status]).map_err(|why| at(format!("{id}'s status {why}")))?;
                check_public(&area).map_err(|why| at(format!("{id}'s area {why}")))?;
                rows.push(Row { area: area.clone(), id, option, status, note });
            }
        }
    }
    Ok(rows)
}

/// A table row's cells, trimmed. `\|` stays escaped and inside its cell, as
/// GitHub reads it; a bare `|` always separates.
fn cells(line: &str) -> Result<Vec<String>, String> {
    let inner = line.trim_end().strip_prefix('|').and_then(|l| l.strip_suffix('|')).filter(|l| !l.ends_with('\\'));
    let Some(inner) = inner else { return Err("a table row must start and end with `|`".into()) };
    let mut out = vec![String::new()];
    let mut escaped = false;
    for c in inner.chars() {
        if c == '|' && !escaped {
            out.push(String::new());
        } else {
            out.last_mut().unwrap().push(c);
        }
        escaped = c == '\\' && !escaped;
    }
    Ok(out.into_iter().map(|cell| cell.trim().to_owned()).collect())
}

/// The option's name: the reference cell's first sentence or clause, without
/// Arc's preference keys in backticks.
fn option_name(cell: &str) -> Result<String, String> {
    let end = [cell.find(". "), cell.find("; ")].into_iter().flatten().min().unwrap_or(cell.len());
    let mut name = cell[..end].trim_end_matches('.').to_owned();
    while let Some(open) = name.find('`') {
        let close = name[open + 1..].find('`').ok_or("has an unclosed backtick")? + open + 1;
        let (mut from, mut to) = (open, close + 1);
        if name[..from].ends_with('(') && name[to..].starts_with(')') {
            from -= 1;
            to += 1;
        }
        name.replace_range(from..to, "");
    }
    let mut name = name.split_whitespace().collect::<Vec<_>>().join(" ").replace(" ,", ",").replace(" )", ")");
    loop {
        let tidy = name.replace(",,", ",").replace(":,", ":").trim_end_matches([' ', ',', ':', ';']).to_owned();
        if tidy == name {
            break;
        }
        name = tidy;
    }
    if name.is_empty() {
        return Err("is empty".into());
    }
    check_public(&name)?;
    Ok(name)
}

/// The status phrases in the cell's leading bold text, without dates and
/// qualifiers: `**SRC (2026-10-29; not native)** — ...` is `SRC`, and
/// `**NONE / DISC placement**` is `NONE / DISC`.
fn status_words(cell: &str) -> Result<String, String> {
    let lead = cell.strip_prefix("**").and_then(|rest| rest.split_once("**")).map(|(lead, _)| lead);
    let Some(lead) = lead else { return Err("must start with the status in **bold**".into()) };
    let mut plain = String::new();
    let mut depth = 0usize;
    for c in lead.chars() {
        match c {
            '(' => depth += 1,
            ')' => depth = depth.saturating_sub(1),
            _ if depth == 0 => plain.push(c),
            _ => {}
        }
    }
    let mut out = String::new();
    let mut joiner: Option<&str> = None;
    let mut adjacent = false;
    for token in plain.split(|c: char| c.is_whitespace() || c == ',').filter(|t| !t.is_empty()) {
        if token == "/" || token == "+" {
            joiner = Some(token);
            adjacent = false;
        } else if token.len() > 1 && token.bytes().all(|b| b.is_ascii_uppercase()) {
            if !out.is_empty() {
                match joiner {
                    Some(j) => out.push_str(&format!(" {j} ")),
                    None if adjacent => out.push(' '),
                    None => return Err(format!("joins `{token}` without `/` or `+`")),
                }
            }
            out.push_str(token);
            joiner = None;
            adjacent = true;
        } else {
            adjacent = false;
        }
    }
    if out.is_empty() {
        return Err("has no status word".into());
    }
    for phrase in out.split(" / ").flat_map(|p| p.split(" + ")) {
        if !LEGEND.iter().any(|(word, _)| *word == phrase) {
            return Err(format!("`{phrase}` has no legend entry in xtask/src/public_parity.rs"));
        }
    }
    Ok(out)
}

/// A public note is one short sentence in plain words.
fn check_note(note: &str) -> Result<(), String> {
    if note.chars().count() > 160 {
        return Err("is longer than 160 characters".into());
    }
    if !note.ends_with('.') {
        return Err("must end with a full stop".into());
    }
    let sentences = note.match_indices(". ").filter(|(i, _)| note[i + 2..].starts_with(|c: char| c.is_uppercase())).count();
    if sentences > 0 {
        return Err("must be one sentence".into());
    }
    check_public(note)
}

/// Refuses what belongs in the roadmap only: code, file names and paths,
/// finding and package IDs, commit hashes and review receipts.
fn check_public(text: &str) -> Result<(), String> {
    if text.contains('`') {
        return Err(format!("has code in backticks: {text}"));
    }
    for root in ["docs/", "app/", "crates/", "cloud/", "xtask/", "src/", "/Users/"] {
        if text.contains(root) {
            return Err(format!("names a path ({root}): {text}"));
        }
    }
    let lower = text.to_ascii_lowercase();
    for word in ["receipt", "recheck", "finding", "coordinator"] {
        if lower.contains(word) {
            return Err(format!("reads as an internal note ({word}): {text}"));
        }
    }
    let bytes = text.as_bytes();
    for (i, _) in text.match_indices('.') {
        let before = i > 0 && (bytes[i - 1].is_ascii_alphanumeric() || bytes[i - 1] == b'_');
        let ext = bytes[i + 1..].iter().take_while(|b| b.is_ascii_lowercase()).count();
        let after = bytes.get(i + 1 + ext).is_none_or(|b| !b.is_ascii_alphanumeric());
        if before && (2..=5).contains(&ext) && after {
            return Err(format!("names a file: {text}"));
        }
    }
    for token in text.split(|c: char| !(c.is_ascii_alphanumeric() || c == '-')).filter(|t| !t.is_empty()) {
        let upper = token.bytes().any(|b| b.is_ascii_uppercase());
        let digit = token.bytes().any(|b| b.is_ascii_digit());
        let lower = token.bytes().any(|b| b.is_ascii_lowercase());
        let hex = token.len() >= 7 && token.bytes().all(|b| b.is_ascii_hexdigit() && !b.is_ascii_uppercase()) && digit && token.bytes().any(|b| b.is_ascii_lowercase());
        // F299, AB1, R8-3, AI-12 and ARC-SET-04 are IDs; E2EE is a word.
        let id = upper && digit && !lower && (token.contains('-') || token.ends_with(|c: char| c.is_ascii_digit()));
        if id || hex {
            return Err(format!("has an ID or hash ({token}): {text}"));
        }
    }
    Ok(())
}

