fn fixture_with(from: &str, to: &str) -> String {
    assert!(FIXTURE.contains(from), "{from}");
    FIXTURE.replacen(from, to, 1)
}

#[test]
fn each_parity_row_keeps_its_area_id_option_status_and_note() {
    let rows = rows(FIXTURE).unwrap();
    let row = |area: &str, id: &str, option: &str, status: &str, note: &str| Row {
        area: area.into(),
        id: id.into(),
        option: option.into(),
        status: status.into(),
        note: note.into(),
    };
    assert_eq!(
        rows,
        [
            row("Settings shell and General", "ASP-G01", "Warn before quitting", "SRC", "An optional switch asks before quitting."),
            row("Settings shell and General", "ASP-G02", "Automatically update", "NONE / DISC", ""),
            row("Settings shell and General", "ASP-G03", "Gmail previews", "SRC + NATIVE PARTIAL", ""),
            row("Badges", "ASP-U01", "Favorite badge controls", "PARTIAL SRC", ""),
        ],
        "the additions table has no Arc option and stays out"
    );
    let (page, count) = render(FIXTURE).unwrap();
    assert_eq!(count, 4);
    assert!(page.starts_with("# Arc Settings parity\n\nGenerated by `cargo xtask public-parity` from the maintainers' own tables"));
    for (word, _) in LEGEND {
        assert!(page.contains(&format!("\n| {word} | ")), "{word}");
    }
    assert!(page.ends_with("| Settings shell and General | ASP-G01 | Warn before quitting | SRC | An optional switch asks before quitting. |\n| Settings shell and General | ASP-G02 | Automatically update | NONE / DISC |  |\n| Settings shell and General | ASP-G03 | Gmail previews | SRC + NATIVE PARTIAL |  |\n| Badges | ASP-U01 | Favorite badge controls | PARTIAL SRC |  |\n"), "{page}");
    for private in ["F299", "ARC-SET", "W1", "simulated", "gmailPreviewEnabled", "Quit asks", "P011", "Transparent"] {
        assert!(!page.contains(private), "{private}");
    }
}

#[test]
fn a_row_the_page_cannot_place_stops_the_command_with_its_line() {
    for (from, to, why) in [
        ("| W1 | An optional", "| W1 | x | An optional", "SOURCE:7: the row has 7 cells; its table has 6"),
        ("| W8 |\n", "|\n", "SOURCE:8: the row has 4 cells; its table has 6"),
        ("**NONE / DISC placement**", "**LATER**", "SOURCE:8: ASP-G02's status `LATER` has no legend entry"),
        ("**NONE / DISC placement**", "**NONE DISC**", "SOURCE:8: ASP-G02's status `NONE DISC` has no legend entry"),
        ("**NONE / DISC placement**", "NONE", "SOURCE:8: ASP-G02's status must start with the status in **bold**"),
        ("**NONE / DISC placement**", "**pending**", "SOURCE:8: ASP-G02's status has no status word"),
        ("**NONE / DISC placement**", "**NONE later DISC**", "SOURCE:8: ASP-G02's status joins `DISC` without `/` or `+`"),
        ("asks before quitting. |", "asks before quitting, see app/src/app.rs. |", "SOURCE:7: ASP-G01's Public note names a path (app/)"),
        ("asks before quitting. |", "asks before quitting (quit.rs). |", "SOURCE:7: ASP-G01's Public note names a file"),
        ("asks before quitting. |", "asks before quitting, fixed in 2a1e1e3. |", "SOURCE:7: ASP-G01's Public note has an ID or hash (2a1e1e3)"),
        ("asks before quitting. |", "asks before quitting after AI-12. |", "SOURCE:7: ASP-G01's Public note has an ID or hash (AI-12)"),
        ("asks before quitting. |", "asks before quitting per `warnBeforeQuit`. |", "SOURCE:7: ASP-G01's Public note has code in backticks"),
        ("asks before quitting. |", "asks before quitting; recheck pending. |", "SOURCE:7: ASP-G01's Public note reads as an internal note (recheck)"),
        ("asks before quitting. |", "asks before quitting. It is off by default. |", "SOURCE:7: ASP-G01's Public note must be one sentence"),
        ("asks before quitting. |", "asks before quitting |", "SOURCE:7: ASP-G01's Public note must end with a full stop"),
        ("| Carrier | Public note |", "| Public note | Carrier |", "SOURCE:5: `Public note` must be the last column"),
        ("| Warn before quitting.", "| `warnBeforeQuit`.", "SOURCE:7: ASP-G01's option name is empty"),
        ("Automatically update. F300.", "Automatically update ARC-SET-04", "SOURCE:8: ASP-G02's option name has an ID or hash (ARC-SET-04)"),
    ] {
        let error = rows(&fixture_with(from, to)).unwrap_err();
        let why = why.replace("SOURCE", SOURCE);
        assert!(error.starts_with(&why), "{from} -> {to}: {error}");
    }
    let long = format!("| W1 | {}. |", "word ".repeat(40).trim_end());
    assert!(rows(&fixture_with("| W1 | An optional switch asks before quitting. |", &long)).unwrap_err().ends_with("Public note is longer than 160 characters"));
    assert_eq!(render("# Nothing here\n").unwrap_err(), format!("{SOURCE} has no parity table"));
}

#[test]
fn the_committed_public_parity_page_is_current() {
    let root = crate::root();
    // A public snapshot has only the page: the roadmap stays private.
    let Ok(source) = std::fs::read_to_string(root.join(SOURCE)) else { return };
    let (page, _) = render(&source).unwrap_or_else(|e| panic!("{e}"));
    let committed = std::fs::read_to_string(root.join(OUTPUT)).unwrap_or_default();
    assert!(committed == page, "{OUTPUT} is stale: run `cargo xtask public-parity` and commit the result");
}
